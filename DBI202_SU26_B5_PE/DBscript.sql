--========================== Create tables =======================================
CREATE TABLE Categories (
    category_id   INT IDENTITY(1,1) PRIMARY KEY,
    category_name VARCHAR(50) NOT NULL
);

CREATE TABLE Publishers (
    publisher_id INT IDENTITY(1,1) PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    country      VARCHAR(50)
);

CREATE TABLE Authors (
    author_id  INT IDENTITY(1,1) PRIMARY KEY,
    full_name  VARCHAR(100) NOT NULL,
    birth_year INT,
    gender varchar(10)
);

CREATE TABLE Members (
    member_id  INT IDENTITY(1,1) PRIMARY KEY,
    full_name  VARCHAR(100) NOT NULL,
    gender varchar(10),
    email      VARCHAR(100) UNIQUE,
    phone      VARCHAR(20),
    join_date  DATE NOT NULL DEFAULT GETDATE(),
    address    VARCHAR(200)
);

CREATE TABLE Books (
    book_id        INT IDENTITY(1,1) PRIMARY KEY,
    title          VARCHAR(200) NOT NULL,
    isbn           VARCHAR(20) UNIQUE,
    published_year INT,
    category_id    INT NOT NULL FOREIGN KEY REFERENCES Categories(category_id),
    publisher_id   INT NOT NULL FOREIGN KEY REFERENCES Publishers(publisher_id),
    total_copies   INT NOT NULL DEFAULT 1
);

CREATE TABLE Book_Authors (
    book_id   INT NOT NULL FOREIGN KEY REFERENCES Books(book_id),
    author_id INT NOT NULL FOREIGN KEY REFERENCES Authors(author_id),
    PRIMARY KEY (book_id, author_id)
);

CREATE TABLE Loans (
    loan_id     INT IDENTITY(1,1) PRIMARY KEY,
    book_id     INT NOT NULL FOREIGN KEY REFERENCES Books(book_id),
    member_id   INT NOT NULL FOREIGN KEY REFERENCES Members(member_id),
    loan_date   DATE NOT NULL,
    due_date    DATE NOT NULL,
    return_date DATE NULL
);
GO

